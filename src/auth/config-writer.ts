/**
 * Helpers for atomically merging secrets into ~/.career-mode/.env and
 * connector settings into ~/.career-mode/config.yaml without clobbering
 * unrelated keys in either file.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync } from "fs";
import { homedir } from "os";
import { join } from "path";

const CAREER_MODE_DIR = join(homedir(), ".career-mode");

function careerModeDir(): string {
  if (!existsSync(CAREER_MODE_DIR)) {
    mkdirSync(CAREER_MODE_DIR, { recursive: true });
  }
  return CAREER_MODE_DIR;
}

/**
 * Merge key=value pairs into ~/.career-mode/.env.
 * Existing keys are replaced in-place; new keys are appended.
 * File permissions are set to 0600 (owner read/write only).
 */
export function writeEnvSecrets(secrets: Record<string, string>): void {
  const dir = careerModeDir();
  const envPath = join(dir, ".env");

  let lines: string[] = existsSync(envPath)
    ? readFileSync(envPath, "utf-8").split("\n")
    : [];

  for (const [key, value] of Object.entries(secrets)) {
    const prefix = `${key}=`;
    const lineIndex = lines.findIndex((l) => l.startsWith(prefix) || l.startsWith(`${key} =`));
    const newLine = `${key}=${value}`;
    if (lineIndex !== -1) {
      lines[lineIndex] = newLine;
    } else {
      lines.push(newLine);
    }
  }

  // Remove trailing blank lines except one
  while (lines.length > 1 && lines[lines.length - 1] === "" && lines[lines.length - 2] === "") {
    lines.pop();
  }

  writeFileSync(envPath, lines.join("\n") + "\n", { encoding: "utf-8", mode: 0o600 });
}

/**
 * Merge top-level key: value pairs into ~/.career-mode/config.yaml.
 * Existing keys are replaced; keys that do not exist are appended.
 * Comments and unrelated config are preserved.
 */
export function writeConfigYaml(fields: Record<string, string>): void {
  const dir = careerModeDir();
  const configPath = join(dir, "config.yaml");

  let lines: string[] = existsSync(configPath)
    ? readFileSync(configPath, "utf-8").split("\n")
    : [
        "# Career Mode configuration — auto-generated by `career-mode auth`",
        "experience_level: senior",
        "tone: balanced",
        "output_dir: ~/.career-mode/artifacts",
      ];

  for (const [key, value] of Object.entries(fields)) {
    // Match `key: ...` at line start, ignoring commented-out lines
    const keyRegex = new RegExp(`^(${key}:\\s*)(.*)$`);
    const commentedRegex = new RegExp(`^#\\s*${key}:`);
    const lineIndex = lines.findIndex((l) => keyRegex.test(l) && !l.startsWith("#"));

    if (lineIndex !== -1) {
      lines[lineIndex] = `${key}: ${value}`;
    } else {
      // If there is a commented-out version, insert the live line right after it
      const commentedIndex = lines.findIndex((l) => commentedRegex.test(l));
      if (commentedIndex !== -1) {
        lines.splice(commentedIndex + 1, 0, `${key}: ${value}`);
      } else {
        lines.push(`${key}: ${value}`);
      }
    }
  }

  writeFileSync(configPath, lines.join("\n") + "\n", { encoding: "utf-8" });
}
